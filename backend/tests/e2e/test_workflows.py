"""Browser-driven regression coverage. Services and database are owned by run_e2e.py."""
from __future__ import annotations

import os
import unittest
from pathlib import Path

from playwright.sync_api import Browser, Page, Playwright, expect


class BrowserWorkflowTests(unittest.TestCase):
    browser: Browser
    playwright: Playwright
    browser_errors: list[str] = []
    failed_requests: list[str] = []

    def setUp(self) -> None:
        self.context = self.browser.new_context()
        self.page: Page = self.context.new_page()
        self.page.set_default_timeout(8_000)
        self.errors: list[str] = []
        self.requests: list[str] = []
        self.page.on("pageerror", lambda error: self.errors.append(str(error)))
        self.page.on("console", lambda message: self.errors.append(message.text) if message.type == "error" else None)
        self.page.on("requestfailed", lambda request: self.requests.append(f"{request.method} {request.url}: {request.failure}"))
        self.base = os.environ["SORKINS_E2E_URL"]
        self.api = os.environ["SORKINS_E2E_API"]
        self.artifacts = Path(os.environ["SORKINS_E2E_ARTIFACTS"])

    def tearDown(self) -> None:
        result = getattr(self._outcome, "result", None)
        failed = bool(result and any(test is self for test, _ in result.failures + result.errors))
        if failed:
            self.page.screenshot(path=str(self.artifacts / f"{self.id().split('.')[-1]}.png"), full_page=True)
        type(self).browser_errors.extend(f"{self.id()}: {item}" for item in self.errors)
        type(self).failed_requests.extend(f"{self.id()}: {item}" for item in self.requests)
        self.context.close()

    def api_json(self, method: str, path: str, data=None):
        response = self.page.request.fetch(self.api + path, method=method, data=data)
        self.assertLess(response.status, 400, f"{method} {path}: {response.status} {response.text()}")
        return response.json() if response.status != 204 else None

    def create_project(self, title: str, setup: bool = False):
        return self.api_json("POST", "/api/projects", {
            "title": title, "format": "Short Film", "premise": "",
            "setup_flow": setup,
        })

    def open_project(self, project_id: int) -> None:
        self.page.goto(self.base)
        self.page.wait_for_load_state("domcontentloaded")
        self.page.locator(".setup-project-name, .project-title").wait_for(state="visible", timeout=15_000)
        projects = self.api_json("GET", "/api/projects")
        target = next(item for item in projects if item["id"] == project_id)
        current = self.page.locator(".setup-project-name, .project-title").first.inner_text()
        if target["title"] not in current:
            self.page.locator(".project-title").wait_for(state="visible", timeout=5_000)
            self.page.locator(".project-title").click()
            self.page.get_by_role("button", name=target["title"], exact=False).click()
            expect(self.page.locator(".setup-project-name, .project-title").first).to_contain_text(target["title"])
        # A fresh local test project may show the first-use welcome; dismiss it without changing shared defaults.
        explore = self.page.get_by_role("button", name="Explore on my own")
        if explore.is_visible():
            explore.click()
        dismiss_tip = self.page.get_by_role("button", name="Dismiss", exact=True)
        if dismiss_tip.is_visible():
            dismiss_tip.click()

